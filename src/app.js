/* ---------------------------------------------------------------- run (neon compile) */
// P / F11: neon light travels from the Start along the links, one step every 2 s (1 s / 0.5 s selectable).
// Where the flow splits, the light splits and every branch keeps going side by side; a node is lit once
// (first arrival wins). Prompts and AI notes linked to a step light up with it. When nothing is left the run
// ends like a compiler: what was reached, what was never reached, and branches that go nowhere.
const RUN_SPEEDS = [2000, 1000, 500];
const RUN_LINKS = new Set(['flow', 'cause', 'require', 'uses']);
/** Kinds that are steps of a flow — unreached ones and dead ends are reported */
const STEP_TYPES = new Set(['start', 'feature', 'task', 'event', 'choice', 'condition', 'loop', 'quest', 'scene', 'dialogue', 'test', 'bug']);
const runStep = () => RUN_SPEEDS[(ui.playing && ui.playing.speed) || 0];
/** Directed edges along structural links (group ends expanded to their members) */
function runEdges(b) {
  const out = new Map();
  for (const l of allLinks(b)) {
    if (!RUN_LINKS.has(l.type)) continue;
    for (const a of endIds(l.from)) for (const c of endIds(l.to)) {
      if (a === c) continue;
      if (!out.has(a)) out.set(a, []);
      out.get(a).push({ id: l.id, from: a, to: c, port: l.from.port });
    }
  }
  return out;
}
function runStarts(b, out, from) {
  if (from && nodeById(from)) return [from];
  const starts = b.nodes.filter(n => n.type === 'start').map(n => n.id);
  if (starts.length) return starts;
  const hasIn = new Set(); for (const es of out.values()) for (const e of es) hasIn.add(e.to);
  const roots = b.nodes.filter(n => !isAiNode(n) && out.has(n.id) && !hasIn.has(n.id)).map(n => n.id);
  return roots.length ? roots : b.nodes.filter(n => !isAiNode(n)).slice(0, 1).map(n => n.id);
}
function startPlay(from) {
  if (!S) return;
  stopPlay(true);
  const b = board(), out = runEdges(b), starts = runStarts(b, out, from);
  if (!starts.length) return toast('Nothing to run — add a Start node and link the steps');
  const r = ui.playing = { out, step: 1, active: new Set(starts), seen: new Set(starts), done: new Set(), live: new Set(), next: new Set(),
    lit: new Set(), litLinks: new Set(), doneLinks: new Set(), branches: 0, speed: Settings.runSpeed || 0, timer: 0, finished: false, report: null, open: false };
  for (const n of b.nodes) if (n.type === 'aiguide') r.lit.add(n.id);   // AI Rules apply to every step: they glow from the beginning
  clearSel(); runLight(r.active); runPrepare();
  world.style.setProperty('--step', runStep() + 'ms');
  world.classList.add('running'); $('#app').classList.add('run-on');
  updateSelectionUI(); renderPlay(); runFollow();
  r.timer = setTimeout(runTick, runStep());
}
function stopPlay(silent) {
  if (!ui.playing) return;
  clearTimeout(ui.playing.timer); ui.playing = null;
  world.classList.remove('running'); $('#app').classList.remove('run-on');
  $('#runBar').classList.remove('show');
  if (!silent && S) { applyClasses(); renderToolbarState(); queueMinimap(); }
}
/** Light the prompts / AI notes linked to these nodes (directly or through their group) */
function runLight(ids) {
  const r = ui.playing, b = board();
  for (const l of allLinks(b)) {
    const fs = endIds(l.from), ts = endIds(l.to);
    for (const id of ids) {
      const other = fs.includes(id) ? ts : ts.includes(id) ? fs : null; if (!other) continue;
      for (const o of other) if (isAiNode(nodeById(o))) { r.lit.add(o); r.litLinks.add(l.id); }
    }
  }
}
/** Links leaving the active nodes towards nodes not reached yet carry the light during this step */
function runPrepare() {
  const r = ui.playing; r.live = new Set(); r.next = new Set();
  for (const id of r.active) {
    const targets = new Set();
    for (const e of r.out.get(id) || []) {
      const t = nodeById(e.to);
      if (!t || isAiNode(t) || r.seen.has(e.to)) continue;
      r.live.add(e.id); r.next.add(e.to); targets.add(e.to);
    }
    if (targets.size > 1) r.branches += targets.size - 1;   // the light splits here
  }
}
function runTick() {
  const r = ui.playing; if (!r) return;
  r.active.forEach(id => r.done.add(id)); r.live.forEach(id => r.doneLinks.add(id));
  if (!r.next.size) return runFinish();
  r.active = r.next; r.active.forEach(id => r.seen.add(id)); r.step++;
  runLight(r.active); runPrepare();
  world.style.setProperty('--step', runStep() + 'ms');
  applyClasses(); renderPlay(); runFollow(); queueMinimap();
  r.timer = setTimeout(runTick, runStep());
}
function runFinish() {
  const r = ui.playing, b = board();
  r.finished = true; r.active = new Set(); r.live = new Set(); r.next = new Set();
  const warn = [];
  for (const n of b.nodes) if (STEP_TYPES.has(n.type) && !r.done.has(n.id)) warn.push({ id: n.id, kind: 'miss', text: `Never reached: ${typeOf(n).name} “${n.title || 'Untitled'}”` });
  for (const n of b.nodes) {
    if (!r.done.has(n.id) || !STEP_TYPES.has(n.type)) continue;
    const es = r.out.get(n.id) || [];
    if (!n.outputs.length) continue;
    if (!es.length) { warn.push({ id: n.id, kind: 'open', text: `Dead end: ${typeOf(n).name} “${n.title || 'Untitled'}” leads nowhere` }); continue; }
    if (n.outputs.length > 1) for (const o of n.outputs) if (!es.some(e => e.port === o.id)) warn.push({ id: n.id, kind: 'open', text: `Open branch: “${n.title || 'Untitled'}” → ${o.label || 'port'} goes nowhere` });
  }
  const counted = b.nodes.filter(n => !isAiNode(n) && !['note', 'doc', 'lore'].includes(n.type));   // notes & docs are reference, not steps
  const rs = b.nodes.filter(n => n.type === 'result'), cnt = k => rs.filter(n => ((n.result && n.result.status) || 'none') === k).length;
  for (const n of rs) if (n.result && n.result.status === 'fail') warn.push({ id: n.id, kind: 'fail', text: 'Result failed: “' + (n.title || 'Untitled') + '”' + (n.result.value ? ' — ' + n.result.value : '') });
  r.report = { reached: counted.filter(n => r.done.has(n.id)).length, total: counted.length, warn, results: rs.length ? { pass: cnt('pass'), fail: cnt('fail'), predicted: cnt('predicted') + cnt('info'), waiting: cnt('none') } : null };
  applyClasses(); renderPlay(); queueMinimap(); renderToolbarState();
  toast(warn.length ? `Run finished · ${warn.length} warning${warn.length > 1 ? 's' : ''}` : 'Run finished · every step was reached');
}
