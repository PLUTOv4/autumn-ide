function inlineEdit(el, obj, field, after) {
  if (!el || el.isContentEditable) return;
  const before = S ? snap() : null, old = obj[field] ?? '';
  el.textContent = old; el.contentEditable = 'plaintext-only'; el.classList.add('editing'); el.focus();
  const range = document.createRange(); range.selectNodeContents(el);
  if (field === 'body') range.collapse(false);
  const s = getSelection(); s.removeAllRanges(); s.addRange(range);
  let cancelled = false;
  const multiline = el.classList.contains('n-body');
  const onKey = ev => {
    ev.stopPropagation();
    if (ev.key === 'Escape') { cancelled = true; el.blur(); }
    else if (ev.key === 'Enter' && (!multiline || ev.ctrlKey)) { ev.preventDefault(); el.blur(); }
  };
  const onInput = () => renderLinks();
  el.addEventListener('keydown', onKey); el.addEventListener('input', onInput);
  el.addEventListener('blur', () => {
    el.removeEventListener('keydown', onKey); el.removeEventListener('input', onInput);
    el.contentEditable = 'false'; el.classList.remove('editing');
    const val = el.innerText.replace(/\n+$/, '');
    if (!cancelled && val !== old) { if (before) pushHistory(before); obj[field] = val; }
    if (after) after(); else changed();
  }, { once: true });
}

