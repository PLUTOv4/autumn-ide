/** The JSON object in an AI answer (plain, or in a code fence) */
function parseAiResult(text) {
  const t = String(text || '').trim(), tries = [];
  const fence = t.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) tries.push(fence[1]);
  const a = t.indexOf('{'), z = t.lastIndexOf('}');
  if (a >= 0 && z > a) tries.push(t.slice(a, z + 1));
  for (const c of tries) { try { const o = JSON.parse(c); if (o && typeof o === 'object') return o; } catch (_) {} }
  return null;
}
