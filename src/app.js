async function autoSave() {
  if (!S) return;
  const text = serialize();
  if (Host.kind === 'browser') Host.saveRecovery(text);
  if (doc.path && Settings.autosave) await writeDoc(text);
  else if (!doc.path) { Host.saveRecovery(text); }
}
async function writeDoc(text, force) {
  if (text === doc.savedText && !force) { doc.dirty = false; updateTitle(); renderStatus(); return true; }
  try {
    await Host.save(doc.path, text, force);
    doc.savedText = text; doc.dirty = false; doc.lastSaved = new Date(); doc.error = null;
    updateTitle(); renderStatus(); return true;
  } catch (e) { doc.error = e.message || String(e); renderStatus(); toast('Save failed: ' + doc.error); return false; }
}
async function saveNow() {
  if (!S) return false;
  clearTimeout(doc.timer);
  if (!doc.path) return saveAs();
  const ok = await writeDoc(serialize(), true);
  if (ok) toast('Saved · ' + basename(doc.path));
  return ok;
}
async function saveAs() {
  if (!S) return false;
  const text = serialize();
  const p = await Host.saveAs(suggestName(), text);
  if (!p) return false;
  doc.path = p; doc.savedText = text; doc.dirty = false; doc.lastSaved = new Date();
  Host.saveRecovery(null);
  updateTitle(); renderStatus(); toast('Saved to ' + basename(p) + (Settings.autosave ? ' · autosave on' : ''));
  return true;
}
