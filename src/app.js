function cleanAi(a) {
  if (!a || typeof a !== 'object') return null;
  const o = {}; for (const f of AI_FIELDS) if (a[f.k]) o[f.k] = String(a[f.k]);
  return o;
}
/** A Result node's last report: { status: pass|fail|info|predicted, value, output, source: run|predicted, by, at } */
function cleanResult(r) {
  const o = { status: r.status };
  for (const k of ['value', 'output', 'note', 'source', 'by', 'at']) if (r[k] != null && r[k] !== '') o[k] = String(r[k]).slice(0, k === 'output' ? 20000 : k === 'note' ? 2000 : 300);
  return o;
}
function cleanSpec(s) {
  const o = {}; if (!s || typeof s !== 'object') return o;
  for (const [k, v] of Object.entries(s)) if (v != null && v !== '' && /^[\w-]{1,40}$/.test(k)) o[k] = String(v);
  return o;
}
