function normalize(p) {
  if (!p || !Array.isArray(p.boards) || !p.boards.length) throw new Error('Not an Autumn project (no boards)');
  const out = { app: 'autumn', format: 1, name: p.name || 'Project', active: p.active, boards: [] };
  out.templates = Array.isArray(p.templates) ? Fields.cleanTemplates(p.templates) : Fields.defaultTemplates();   // objects (templates)
  const v0 = p.boards[0].view;
  out._hadView = !!v0 && !(v0.x === 240 && v0.y === 160 && v0.z === 1);
  for (const b0 of p.boards) {
    const b = { id: b0.id || uid('b'), name: b0.name || 'Board', nodes: [], links: [], groups: [], view: Object.assign({ x: 240, y: 160, z: 1 }, b0.view || {}) };
    b.nodes = (b0.nodes || []).map(n => {
      const t = TYPES[n.type] ? n.type : 'note';
      const images = (Array.isArray(n.images) ? n.images : []).map(cleanImage).filter(Boolean);
      if (n.image && !images.length) images.push(cleanImage({ data: n.image, name: 'Image' }));   // 1.0 older format
      const node = Object.assign(makeNode(t, 0, 0), n, {
        type: t, tags: Array.isArray(n.tags) ? n.tags : [], status: STATUS[n.status] ? n.status : 'idea', w: n.w || 250,
        outputs: Array.isArray(n.outputs) ? n.outputs.map(o => ({ id: o.id || uid('p'), label: o.label ?? '' })) : TYPES[t].outs.map(l => ({ id: uid('p'), label: l })),
        images, data: Fields.cleanFields(n.data),
      });
      if (!node.dataHidden) delete node.dataHidden;
      if (node.h > 0) node.h = Math.round(node.h); else delete node.h;   // Only nodes with a manually set height have h (otherwise height fits the content)
      const ai = cleanAi(n.ai);
      if (AI_TYPES.has(t) || (ai && Object.keys(ai).length)) node.ai = ai || {}; else delete node.ai;
      if (n.result && typeof n.result === 'object' && RESULT_STATUS[n.result.status]) node.result = cleanResult(n.result); else delete node.result;
      const spec = cleanSpec(n.spec);
      if (SPEC_FIELDS[t] || Object.keys(spec).length) node.spec = spec; else delete node.spec;
      delete node.image;
      if (node.imageMode !== 'native') delete node.imageMode;
      return node;
    });
    const ports = new Map(b.nodes.map(n => [n.id, new Set(n.outputs.map(o => o.id))]));
    b.links = (b0.links || []).filter(l => l.from && l.to && ports.has(l.from.node) && ports.has(l.to.node))
      .map(l => {
        let port = l.from.port;
        if (!ports.get(l.from.node).has(port)) port = nodeById(l.from.node, b)?.outputs[0]?.id;
        return port ? { id: l.id || uid('l'), from: keepSide(l.from, { node: l.from.node, port }, true, ports), to: keepSide(l.to, { node: l.to.node }, false, ports), type: linkTypeOf(l.type, 'flow'), label: l.label || '' } : null;
      }).filter(Boolean);
    b.groups = (b0.groups || []).map(g => Object.assign({ id: uid('g'), x: 0, y: 0, w: 400, h: 300, title: 'Group', color: COLORS[5] }, g));
    // Group links: one (or both) ends is a group. A group stands for all nodes inside it
    const gids = new Set(b.groups.map(g => g.id));
    const end = (e, out) => {
      if (!e) return null;
      if (e.group) return gids.has(e.group) ? keepSide(e, { group: e.group }, out, ports) : null;
      if (!ports.has(e.node)) return null;
      if (!out) return keepSide(e, { node: e.node }, false, ports);
      const port = ports.get(e.node).has(e.port) ? e.port : nodeById(e.node, b)?.outputs[0]?.id;
      return port ? keepSide(e, { node: e.node, port }, true, ports) : null;
    };
    b.groupLinks = (b0.groupLinks || []).map(l => {
      const from = end(l.from, true), to = end(l.to, false);
      if (!from || !to || !(from.group || to.group) || (from.group && from.group === to.group)) return null;
      return { id: l.id || uid('l'), from, to, type: linkTypeOf(l.type, 'relation'), label: l.label || '' };
    }).filter(Boolean);
    out.boards.push(b);
  }
  if (!out.boards.find(b => b.id === out.active)) out.active = out.boards[0].id;
  return out;
}
/* Which side a link end attaches to: side 'l'(left dot) / 'r'(right dot). Default is sender = right, receiver = left, so it is stored only when different.
   If the receiving end is attached to a right output dot, at = that output port id (which dot to attach to) */
const defSide = isFrom => isFrom ? 'r' : 'l';
function keepSide(src, dst, isFrom, ports) {
  const side = src && src.side;
  if ((side === 'l' || side === 'r') && side !== defSide(isFrom)) {
    dst.side = side;
    if (!isFrom && side === 'r' && src.at && dst.node && (!ports || ports.get(dst.node)?.has(src.at))) dst.at = src.at;
  }
  return dst;
}
/** If dropped on a dot: its side (l/r) and output port id */
function dropSide(el) {
  const pt = el?.closest('.port, .gport'); if (!pt) return null;
  return { side: pt.classList.contains('in') ? 'l' : 'r', port: pt.dataset.port || null };
}
