/** Steps that lead into a Result node (backwards along every link except AI links), in flow order */
function resultChain(n, max = 16) {
  const links = allLinks(), seen = new Set([n.id]), found = [];
  let front = [n.id];
  while (front.length && found.length < max) {
    const next = [];
    for (const id of front) for (const l of links) {
      if (l.type === 'ai' || !endIds(l.to).includes(id)) continue;
      for (const f of endIds(l.from)) {
        if (seen.has(f)) continue;
        seen.add(f);
        const x = nodeById(f);
        if (x && !isAiNode(x)) { found.push(x); next.push(f); }
      }
    }
    front = next;
  }
  const order = Spec.flowOrder(board()).flow.map(x => x.id), rank = x => { const i = order.indexOf(x.id); return i < 0 ? -1 : i; };
  return found.slice(0, max).sort((a, c) => rank(a) - rank(c));
}
