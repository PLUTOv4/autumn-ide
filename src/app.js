/** A spot where a frame of group g’s size overlaps no other group · node: right → below → bottom of the board */
function freeSpotFor(g, gap = 60) {
  const b = board();
  const boxes = b.groups.map(x => ({ x1: x.x, y1: x.y, x2: x.x + x.w, y2: x.y + x.h }))
    .concat(b.nodes.map(n => ({ x1: n.x, y1: n.y, x2: n.x + nodeW(n), y2: n.y + nodeH(n.id) })));
  const free = (x, y) => !boxes.some(r => x < r.x2 + gap / 2 && x + g.w > r.x1 - gap / 2 && y < r.y2 + gap / 2 && y + g.h > r.y1 - gap / 2);
  const tries = [{ x: g.x + g.w + gap, y: g.y }, { x: g.x, y: g.y + g.h + gap }];
  for (const p of tries) if (free(p.x, p.y)) return { x: snapV(p.x), y: snapV(p.y) };
  const bottom = Math.max(...boxes.map(r => r.y2));
  return { x: snapV(g.x), y: snapV(bottom + gap) };
}
