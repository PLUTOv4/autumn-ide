/** Link type from a file; 'join' (older WorldThink battle links) becomes 'uses' */
const linkTypeOf = (t, def) => LINK_TYPES[t] ? t : t === 'join' ? 'uses' : def;
/** Link type picked automatically from the two node kinds (when the brush is Flow) */
function autoLinkType(a, c) {
  if (isAiNode(a) || isAiNode(c)) return 'ai';
  if (a.type === 'character' && c.type === 'character') return 'relation';
  if (a.type === 'data' || (CODE_TYPES.has(a.type) && CODE_TYPES.has(c.type) && a.type !== 'test' && a.type !== 'bug')) return 'uses';
  if (a.type === 'item') return 'require';
  if (a.type === 'lore' || a.type === 'note' || a.type === 'doc') return 'ref';
  if (a.type === 'character' || a.type === 'location') return 'relation';
  return 'flow';
}
function defaultLinkType(fromId, toId) {
  if (ui.brush !== 'flow') return ui.brush;
  const a = nodeById(fromId), c = nodeById(toId);
  return a && c ? autoLinkType(a, c) : 'flow';
}
function addLinkRaw(from, port, to, type, label = '') {
  const b = board();
  if (from === to) return null;
  if (b.links.some(l => l.from.node === from && l.from.port === port && l.to.node === to)) return null;
  const l = { id: uid('l'), from: { node: from, port }, to: { node: to }, type: type || defaultLinkType(from, to), label };
  b.links.push(l); return l;
}
/* A link end is a node({node, port}) or a group({group}). Links involving a group live in board.groupLinks */
const endKey = e => e.group ? 'g:' + e.group : e.node;
const isGroupLink = l => !!(l.from.group || l.to.group);
const allLinks = (b = board()) => b.links.concat(b.groupLinks);
function defaultGroupLinkType(from, to) {
  if (ui.brush !== 'flow') return ui.brush;
  const a = from.node && nodeById(from.node), c = to.node && nodeById(to.node);
  if (isAiNode(a) || isAiNode(c)) return 'ai';
  if (a?.type === 'item') return 'require';
  if (a?.type === 'lore' || a?.type === 'note' || a?.type === 'doc') return 'ref';
  if (CODE_TYPES.has(a?.type) || CODE_TYPES.has(c?.type)) return 'uses';
  return 'relation';
}
function addGroupLink(from, to, type, label = '') {
  const b = board();
  if (endKey(from) === endKey(to)) return null;
  if (b.groupLinks.some(l => endKey(l.from) === endKey(from) && (l.from.port || '') === (from.port || '') && endKey(l.to) === endKey(to))) return null;
  const l = { id: uid('l'), from: from.group ? { group: from.group } : { node: from.node, port: from.port }, to: to.group ? { group: to.group } : { node: to.node }, type: type || defaultGroupLinkType(from, to), label };
  b.groupLinks.push(l); return l;
}
/** When deleting nodes · groups, also delete group links attached to them */
function dropGroupLinks(b, nodeIds, groupIds) {
  b.groupLinks = b.groupLinks.filter(l => !(nodeIds && (nodeIds.has(l.from.node) || nodeIds.has(l.to.node))) && !(groupIds && (groupIds.has(l.from.group) || groupIds.has(l.to.group))));
}
