window.addEventListener('keydown', e => {
  const ctrl = e.ctrlKey || e.metaKey, k = e.key, lk = k.toLowerCase();
  if (ctrl && lk === 's') { e.preventDefault(); document.activeElement?.blur?.(); e.shiftKey ? saveAs() : saveNow(); return; }
  if (ctrl && lk === 'o') { e.preventDefault(); cmdOpen(); return; }
  if (ctrl && lk === 'n') { e.preventDefault(); newProject(); return; }
  if (vw.open) {
    if (k === 'Escape') closeViewer(); else if (k === 'ArrowRight') viewerStep(1); else if (k === 'ArrowLeft') viewerStep(-1);
    else if (k === '0') zoomViewer(1 / devicePixelRatio); else if (lk === 'f') viewerFit();
    if (!ctrl) e.preventDefault(); return;
  }
  if (k === 'F1') { e.preventDefault(); showShortcuts(); return; }
  if (k === 'F11') { e.preventDefault(); if (S && !$('#modal').classList.contains('show')) CMD.play(); return; }   // Run (like F5 in an IDE)
  if (isTyping(e.target)) return;
  if ($('#modal').classList.contains('show')) { if (k === 'Escape') closeModal(); return; }
  if (menu.style.display === 'block' && k === 'Escape') { hideMenu(); return; }
  if (!S) return;
  if (k === 'Escape' && ui.playing) { stopPlay(); return; }
  if (k === 'Escape' && ui.trace) { CMD.trace(); return; }
  if (k === ' ' && !ui.space) { ui.space = true; vp.classList.add('grab'); e.preventDefault(); return; }
  if (ctrl) {
    if (lk === 'z' && !e.shiftKey) { e.preventDefault(); undo(); }
    else if (lk === 'y' || (lk === 'z' && e.shiftKey)) { e.preventDefault(); redo(); }
    else if (lk === 'a') { e.preventDefault(); selectAll(); }
    else if (lk === 'd') { e.preventDefault(); duplicate(); }
    else if (lk === 'g') { e.preventDefault(); groupSelection(); }
    else if (lk === 'f') { e.preventDefault(); openFind(); }
    else if (lk === 'b') { e.preventDefault(); CMD.toggleSide(); }
    else if (lk === 'j') { e.preventDefault(); CMD.toggleInsp(); }
    else if (k === '=' || k === '+') { e.preventDefault(); zoomCenter(1.2); }
    else if (k === '-') { e.preventDefault(); zoomCenter(1 / 1.2); }
    return;
  }
  if (e.altKey) return;
  switch (k) {
    case 'Delete': case 'Backspace': e.preventDefault(); deleteSelection(); break;
    case 'Escape': closeSearch(); hideMenu(); clearSel(); updateSelectionUI(); break;
    case 'f': case 'F': fitView(true); break;
    case '0': zoomCenter(1); break;
    case '+': case '=': zoomCenter(1.2); break;
    case '-': zoomCenter(1 / 1.2); break;
    case 'l': case 'L': autoLayout(); break;
    case 't': case 'T': CMD.trace(); break;
    case 'p': case 'P': CMD.play(); break;
    case 'c': case 'C': toggleCollapse(); break;
    case 'Enter': if (ui.sel.size === 1) { e.preventDefault(); editBody([...ui.sel][0]); } break;
    case 'ArrowLeft': case 'ArrowRight': case 'ArrowUp': case 'ArrowDown': {
      if (!ui.sel.size) return; e.preventDefault(); const s = e.shiftKey ? 50 : GRID;
      nudge(k === 'ArrowLeft' ? -s : k === 'ArrowRight' ? s : 0, k === 'ArrowUp' ? -s : k === 'ArrowDown' ? s : 0); break;
    }
  }
});
