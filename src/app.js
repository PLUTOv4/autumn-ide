function autoLayout() {
  if (!S) return;
  const b = board();
  const ns = ui.sel.size > 1 ? selNodes() : b.nodes;
  if (ns.length < 2) return toast('Not enough nodes to arrange');
  const ids = new Set(ns.map(n => n.id));
  const ls = b.links.filter(l => ids.has(l.from.node) && ids.has(l.to.node) && l.from.node !== l.to.node && (l.type === 'flow' || l.type === 'cause'));
  const out = new Map(), deg = new Map();
  ns.forEach(n => { out.set(n.id, []); deg.set(n.id, 0); });
  ls.forEach(l => { out.get(l.from.node).push(l); deg.set(l.to.node, deg.get(l.to.node) + 1); });
  const connected = new Set(); ls.forEach(l => { connected.add(l.from.node); connected.add(l.to.node); });
  const flow = ns.filter(n => connected.has(n.id)), loose = ns.filter(n => !connected.has(n.id));
  const rank = new Map(), done = new Set();
  const queue = flow.filter(n => deg.get(n.id) === 0).sort((a, c) => a.y - c.y).map(n => n.id);
  while (done.size < flow.length) {
    if (!queue.length) { const rem = flow.filter(n => !done.has(n.id)).sort((a, c) => deg.get(a.id) - deg.get(c.id) || a.x - c.x)[0]; queue.push(rem.id); }
    const id = queue.shift(); if (done.has(id)) continue;
    done.add(id); if (!rank.has(id)) rank.set(id, 0);
    for (const l of out.get(id)) {
      const t = l.to.node; if (done.has(t)) continue;
      rank.set(t, Math.max(rank.get(t) ?? 0, rank.get(id) + 1));
      deg.set(t, deg.get(t) - 1); if (deg.get(t) <= 0) queue.push(t);
    }
  }
  const cols = [];
  flow.forEach(n => { const r = rank.get(n.id); (cols[r] = cols[r] || []).push(n); });
  const order = new Map();
  cols.forEach((col, ci) => {
    if (!col) return;
    if (ci === 0) col.sort((a, c) => a.y - c.y);
    else {
      const bc = new Map();
      col.forEach(n => {
        const ps = ls.filter(l => l.to.node === n.id && order.has(l.from.node)).map(l => order.get(l.from.node) + nodeById(l.from.node).outputs.findIndex(o => o.id === l.from.port) * 0.1);
        bc.set(n.id, ps.length ? ps.reduce((a, c) => a + c, 0) / ps.length : 1e6 + n.y);
      });
      col.sort((a, c) => bc.get(a.id) - bc.get(c.id));
    }
    col.forEach((n, i) => order.set(n.id, i));
  });
  const gapX = 90, gapY = 40;
  const x0 = snapV(Math.min(...ns.map(n => n.x))), y0 = snapV(Math.min(...ns.map(n => n.y)));
  const colW = cols.map(c => c ? Math.max(...c.map(n => n.w)) : 0);
  const colH = cols.map(c => c ? c.reduce((s, n) => s + nodeH(n.id), 0) + gapY * (c.length - 1) : 0);
  const maxH = Math.max(0, ...colH), target = new Map();
  let x = x0;
  cols.forEach((c, ci) => { if (!c) return; let y = y0 + (maxH - colH[ci]) / 2; c.forEach(n => { target.set(n.id, { x: snapV(x), y: snapV(y) }); y += nodeH(n.id) + gapY; }); x += colW[ci] + gapX; });
  const rowMax = Math.max(x - x0, 1100);
  let lx = x0, ly = y0 + maxH + (flow.length ? 140 : 0), rowH = 0;
  const typeOrder = Object.keys(TYPES);
  loose.sort((a, c) => typeOrder.indexOf(a.type) - typeOrder.indexOf(c.type) || a.x - c.x).forEach(n => {
    if (lx > x0 && lx + n.w > x0 + rowMax) { lx = x0; ly += rowH + gapY; rowH = 0; }
    target.set(n.id, { x: snapV(lx), y: snapV(ly) }); lx += n.w + 40; rowH = Math.max(rowH, nodeH(n.id));
  });
  const groupsMembers = b.groups.map(g => ({ g, m: nodesInGroup(g) })).filter(x => x.m.length && x.m.every(n => ids.has(n.id)));
  pushHistory();
  tweenNodes(target, () => { groupsMembers.forEach(({ g, m }) => fitGroup(g, m)); changed(); });
}
function tweenNodes(target, done) {
  const starts = new Map([...target.keys()].map(id => { const n = nodeById(id); return [id, { x: n.x, y: n.y }]; }));
  const t0 = performance.now(), dur = 420, my = ++ui.tweenId;
  const step = now => {
    if (my !== ui.tweenId) return;
    const k = clamp((now - t0) / dur, 0, 1), e = k < .5 ? 4 * k * k * k : 1 - Math.pow(-2 * k + 2, 3) / 2;
    for (const [id, t] of target) {
      const n = nodeById(id), s = starts.get(id); if (!n) continue;
      n.x = Math.round(s.x + (t.x - s.x) * e); n.y = Math.round(s.y + (t.y - s.y) * e);
      const el = nodeEls.get(id); if (el) { el.style.left = n.x + 'px'; el.style.top = n.y + 'px'; }
    }
    renderLinks(); queueMinimap();
    if (k < 1) requestAnimationFrame(step); else if (done) done();
  };
  requestAnimationFrame(step);
}

