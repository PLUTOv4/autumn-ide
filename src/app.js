// Images are never recompressed or resized. Original bytes as-is
//   · desktop: next to the project file in autumn-assets/<content hash>.<ext>, the JSON stores only the path
//   · browser: no file system, so the original data URL is stored in the JSON
const IMG_EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/gif': 'gif', 'image/webp': 'webp', 'image/bmp': 'bmp', 'image/svg+xml': 'svg', 'image/avif': 'avif' };
function readAsDataURL(file) { return new Promise((res, rej) => { const r = new FileReader(); r.onload = () => res(r.result); r.onerror = () => rej(r.error); r.readAsDataURL(file); }); }
function probeSize(url) { return new Promise(res => { const im = new Image(); im.onload = () => res({ w: im.naturalWidth, h: im.naturalHeight }); im.onerror = () => res({ w: 0, h: 0 }); im.src = url; }); }
async function ensureAssetHome() {
  if (Host.caps.assets !== 'file' || doc.path) return true;
  toast('Images are saved as originals next to the project file — choose where to save first');
  return saveAs();
}
async function importImage(file) {
  const dataUrl = await readAsDataURL(file);
  const { w, h } = await probeSize(dataUrl);
  if (!w) throw new Error(`${file.name || 'Image'}: cannot be read as an image`);
  const mime = file.type || dataUrl.slice(5, dataUrl.indexOf(';'));
  const ext = IMG_EXT[mime] || (file.name.split('.').pop() || 'png').toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 5) || 'png';
  const name = file.name && file.name !== 'image.png' ? file.name : 'pasted image.' + ext;
  const im = { id: uid('i'), name, w, h, bytes: file.size, mime };
  if (Host.caps.assets === 'file') im.file = await Host.putAsset(dataUrl.slice(dataUrl.indexOf(',') + 1), ext);
  else im.data = dataUrl;
  return im;
}
async function importImages(files) {
  if (!(await ensureAssetHome())) return [];
  if (files.length > 1 || files[0].size > 3e6) toast(`Loading ${files.length} image${files.length > 1 ? 's' : ''}…`);
  const out = [];
  for (const f of files) { try { out.push(await importImage(f)); } catch (e) { toast(e.message); } }
  return out;
}
