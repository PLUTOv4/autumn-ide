async function boot() {
  document.body.classList.add('host-' + Host.kind);
  renderToolbar(); renderActivity();
  const init = (await Host.init()) || {};
  Settings = { ...DEFAULT_SETTINGS, ...(init.settings || {}) };
  ui.recent = init.recent || [];
  applyPanels(); renderActivity(); renderToolbarState();
  requestAnimationFrame(() => requestAnimationFrame(() => $('#app').classList.add('anim-ok')));   // no panel animation on the first paint
  Host.onExternal(text => onExternalText(text));
  if (Host.caps.aiCli) Host.aiClis().then(l => { ui.aiClis = l || []; if (ui.sel.size === 1) renderInspector(); }).catch(() => { ui.aiClis = []; });
  Host.onOpenFile(async f => { await flush(); openProjectText(f.text, f.path); });
  Host.onBeforeClose(async () => { try { await flush(); } finally { Host.closeNow(); } });
  if (init.file && init.file.text != null) {
    if (!init.file.text.trim()) { const p = blankProject(projName(init.file.path) || 'New project', true); openProjectText(JSON.stringify(p, null, 2), init.file.path, { fit: true }); markDirty(); }
    else openProjectText(init.file.text, init.file.path);
  } else if (init.recovery) {
    if (openProjectText(init.recovery, null, { dirty: true })) toast('Recovered unsaved work from last time');
    else await showWelcome();
  } else await showWelcome();
  if (document.fonts) document.fonts.ready.then(() => S && renderLinks());
  updateTitle(); renderStatus();
}
