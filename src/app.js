      let dx = dxs / v.z, dy = dys / v.z;
      if (Settings.snap && (!e.altKey || drag.dup)) { dx = snapV(drag.gx + dx) - drag.gx; dy = snapV(drag.gy + dy) - drag.gy; }   // Alt snap to grid even while duplicating
      drag.g.x = drag.gx + dx; drag.g.y = drag.gy + dy;
