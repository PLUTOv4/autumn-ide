const matchQ = (n, q) => (n.title + ' ' + n.body + ' ' + n.tags.join(' ') + ' ' + typeOf(n).name + (n.ai ? ' ' + Object.values(n.ai).join(' ') : '') + (n.spec ? ' ' + Object.values(n.spec).join(' ') : '')).toLowerCase().includes(q);
/** Node ids a link end stands for (a group end = every node inside the group) */
function endIds(e) { if (e.group) { const g = groupById(e.group); return g ? nodesInGroup(g).map(n => n.id) : []; } return [e.node]; }
/** Directed adjacency of the board, with group links expanded to their members */
function linkGraph(b) {
  const out = new Map(), inn = new Map(), add = (m, a, c) => { let s = m.get(a); if (!s) m.set(a, s = new Set()); s.add(c); };
  for (const l of allLinks(b)) { const fs = endIds(l.from), ts = endIds(l.to); for (const a of fs) for (const c of ts) if (a !== c) { add(out, a, c); add(inn, c, a); } }
  return { out, inn };
}
/** Breadth-first walk from the selection → Map(id → steps away). AI-side nodes (prompts, notes, rules) are leaves,
 *  so one prompt linked to many nodes does not pull the whole board into the trace. */
function walkFrom(start, adj) {
  const dist = new Map([...start].map(id => [id, 0])), q = [...start];
  while (q.length) {
    const id = q.shift(), d = dist.get(id);
    if (d > 0 && isAiNode(nodeById(id))) continue;
    for (const c of adj.get(id) || []) if (!dist.has(c)) { dist.set(c, d + 1); q.push(c); }
  }
  return dist;
}
function computeVis() {
  const b = board(); let keep = null;
  ui.up = ui.down = ui.near = ui.depth = null;
  if (ui.sel.size) {
    const g = linkGraph(b);
    ui.up = new Set(); ui.down = new Set();
    for (const id of ui.sel) {
      for (const c of g.out.get(id) || []) if (!ui.sel.has(c)) ui.down.add(c);
      for (const c of g.inn.get(id) || []) if (!ui.sel.has(c)) ui.up.add(c);
    }
    ui.near = new Set([...ui.up, ...ui.down]);
    if (ui.trace) {
      const dir = ui.traceDir || 'both';
      const down = dir !== 'up' ? walkFrom(ui.sel, g.out) : new Map(), up = dir !== 'down' ? walkFrom(ui.sel, g.inn) : new Map();
      ui.depth = { down, up };
      keep = new Set([...down.keys(), ...up.keys(), ...ui.sel]);
    }
  }
  const inter = s => { keep = keep ? new Set([...keep].filter(x => s.has(x))) : s; };
  if (ui.tagFilter) inter(new Set(b.nodes.filter(n => n.tags.includes(ui.tagFilter)).map(n => n.id)));
  if (ui.olq) inter(new Set(b.nodes.filter(n => matchQ(n, ui.olq)).map(n => n.id)));
  ui.vis = keep;
}
function nodeCls(n) {
  let c = 'node t-' + n.type;
  if (ui.sel.has(n.id)) c += ' sel';
  else if (ui.depth) {
    if (ui.depth.down.has(n.id)) c += ' tr-down';
    if (ui.depth.up.has(n.id)) c += ' tr-up';
  } else if (ui.near && ui.near.has(n.id)) {
    if (ui.down.has(n.id)) c += ' near-down';
    if (ui.up.has(n.id)) c += ' near-up';
  }
  if (n.collapsed) c += ' collapsed';
  if (n.h) c += ' sized';
  if (ui.vis && !ui.vis.has(n.id)) c += ' dim';
  if (ui.playing) c += runCls(n.id);
  return c;
}
/** How far (in steps) a traced node is from the selection — closer nodes glow brighter */
function traceDepth(n) {
  if (!ui.depth) return '';
  const d = Math.min(ui.depth.down.get(n.id) ?? 99, ui.depth.up.get(n.id) ?? 99);
  return d < 99 ? `--td:${Math.min(d, 6)};` : '';
}
function linkCls(l) {
  let c = 'link';
  if (isGroupLink(l)) c += ' glink';
  if (l.type === 'ai') c += ' ailink';
  if (ui.selLink === l.id) c += ' sel';
  if (ui.playing) return c + runLinkCls(l);
  const fs = endIds(l.from), ts = endIds(l.to);
  if (ui.depth) {
    const { down, up } = ui.depth;
    if (fs.some(id => down.has(id)) && ts.some(id => down.has(id) && down.get(id) > 0)) c += ' tr-down';
    else if (ts.some(id => up.has(id)) && fs.some(id => up.has(id) && up.get(id) > 0)) c += ' tr-up';
  } else if (ui.sel.size) {
    if (fs.some(id => ui.sel.has(id))) c += ' hl hl-out';
    else if (ts.some(id => ui.sel.has(id))) c += ' hl hl-in';
  }
  if (ui.selGroup && (l.from.group === ui.selGroup || l.to.group === ui.selGroup)) c += ' hl hl-out';
  if (ui.vis && !(fs.some(id => ui.vis.has(id)) && ts.some(id => ui.vis.has(id)))) c += ' dim';
  return c;
}
